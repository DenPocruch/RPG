using UnityEngine;

/// <summary>
/// Поверхность установки мебели в доме (конструктор дома).
/// Разметка хранится в FurnitureMountTable, дефолт — по папке префаба.
/// </summary>
public enum FurnitureMount
{
    Floor = 0, // напольная: стоит на тайле пола, футпринт не лезет в стены
    Wall = 1,  // настенная: висит на тайле стены (snap + кламп целиком)
    Both = 2,  // без разницы (запас на будущее, мелочь без коллайдера)
}
